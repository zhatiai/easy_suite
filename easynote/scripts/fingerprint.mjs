import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

// Hash source bytes and relative paths, independent of checkout, Git and target runtime.
const root = path.resolve(import.meta.dirname, '..');
const output = 'src/shared/codeFingerprint.generated.ts';
const files = [];
async function scan(directory) {
  for (const entry of await readdir(path.join(root, directory), { withFileTypes: true })) {
    const name = `${directory}/${entry.name}`;
    if (name === output) continue;
    if (entry.isDirectory()) await scan(name);
    else if (entry.isFile()) files.push(name);
  }
}
for (const directory of ['src', 'migrations', 'public', 'scripts']) await scan(directory);
files.push('package.json', 'package-lock.json', 'wrangler.json', 'vite.config.ts');
const hash = createHash('sha256');
for (const file of files.sort()) {
  const bytes = await readFile(path.join(root, file));
  hash.update(`${file}\0${bytes.length}\0`);
  hash.update(bytes);
}
const generated = `// Generated by scripts/fingerprint.mjs.\nexport const CODE_FINGERPRINT = '${hash.digest('hex')}';\n`;
let previous;
try { previous = await readFile(path.join(root, output), 'utf8'); }
catch (error) { if (error.code !== 'ENOENT') throw error; }
// Avoid triggering the Wrangler source watcher again when inputs have not changed.
if (previous !== generated) await writeFile(path.join(root, output), generated);
